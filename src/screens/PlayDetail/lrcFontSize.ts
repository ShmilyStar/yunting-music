/**
 * 「歌词字号」设置值 → 实际设计字号。
 *
 * 设置里滑块的取值是 100~300，界面上显示的就是这个数字。用户（2026-10-21）要求：
 * **100 要显示成原来 150 的大小，300 要显示成原来 350 的大小**，即整条曲线的字号
 * 都由「原值 ÷ 10」改为「原值 ÷ 10 + 5」：
 *
 *   设置值 100 → 原来 10 → 现在 15（= 原来 150 的大小）
 *   设置值 300 → 原来 30 → 现在 35（= 原来 350 的大小）
 *
 * 也就是说，滑块**范围不变**，只是同一位置的字号整体放大 5 个设计单位；
 * 默认值 210 会从 21 变成 26。
 *
 * 三处必须共用这一个换算：歌词页（Vertical/Horizontal 的 Lyric）、
 * 主播放页的歌词预览（DetailPage），否则调了设置只有一处变。
 */
export const LRC_FONT_SIZE_OFFSET = 5

/** 设置值（100~300）→ 设计字号 */
export const lrcFontSizeFromSetting = (settingValue: number) => settingValue / 10 + LRC_FONT_SIZE_OFFSET
